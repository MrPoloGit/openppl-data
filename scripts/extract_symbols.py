#!/usr/bin/env python3
"""Extracts OpenPPL's symbol-reference tables from the vendored manual
pages into one structured JSON file.

Per 's own suggestion for OpenPPL ("a script that
extracts them from the manual's symbol reference pages is worth writing"):
this is that script. It is the one place that knows the manual's HTML
structure; everything downstream (the curated registry JSON files under
openppl-data/registry/) should be built from this script's output, not by
hand-transcribing the manual a second time, so the two can't silently
drift apart.

Source pages .

Two distinct HTML shapes are present in these pages, confirmed by
inspection, not assumed uniform:
  1. Most pages: a plain <table> of <tr><td>Name</td><td>Meaning</td>
     [<td>Limitations</td>]</tr> rows, generated by eLyXer or a LaTeX
     "longtable" extension. The latter inserts decorative <hr>-only rows
     between data rows and hard-wraps cell text one word per line; both
     are handled by stripping tags and collapsing whitespace, then
     dropping any row that is empty after that.
  2. Betsizes/PokerTracker page only: NOT a real <table>, eLyXer emitted
     a broken decorative <table> fragment followed by a flat sequence of
     <div class="standard"><a id="magicparlabel-N">TEXT</a></div>
     elements, two per symbol (name, then meaning), grouped under
     <dl><dt class="description_label">Category Name</dt></dl> headers.
     Confirmed by reading the raw HTML directly, not guessed at.

Usage: python3 openppl-data/scripts/extract_symbols.py > openppl-data/registry/raw_symbols.json

**raw_symbols.json is NOT published.** It's a near-verbatim extraction of
the GPLv3-licensed OpenPPL manual's own table cells (name + the manual's
own sentence), gitignored (openppl-data/registry/.gitignore) and regenerated
locally only, for this project's own private reference while writing
openppl-data/registry/symbols.json's independently-worded descriptions, see
that file's _comment and openppl-data/registry/README.md for the full
licensing posture . Never
commit, publish, or otherwise distribute this script's output.
"""
import html
import json
import re
import sys
from pathlib import Path

SOURCE_DIR = Path(__file__).resolve().parent.parent.parent / "docs" / "openppl stuff"

TABLE_PAGES = {
    "bettingaction.html": "BettingAction_Symbols",
    "betsizes.html": "Betsizes_and_Stacksizes",
    "boardsymbols.html": "Board_Symbols",
    "handstrength.html": "Handstrength_Symbols",
    "othersymbols.html": "Other_Symbols",
    "play and opponentsymbols.html": "Player_Symbols",
    "position symbols.html": "Position_Symbols",
    "technical symbols.html": "Technical_Symbols",
}

POKERTRACKER_PAGE = "pokertrackersymbols.html"
POKERTRACKER_LABEL = "PokerTracker_Symbols"


def strip_tags(s: str) -> str:
    s = re.sub(r"<!--.*?-->", "", s, flags=re.S)
    s = re.sub(r"<[^>]+>", " ", s)
    s = html.unescape(s)
    return re.sub(r"\s+", " ", s).strip()


def extract_table_page(path: Path) -> list[dict]:
    content = path.read_text(encoding="utf-8")
    tables = re.findall(r"<table\b.*?</table>", content, re.S)
    entries = []
    for t in tables:
        rows = re.findall(r"<tr\b.*?</tr>", t, re.S)
        for r in rows:
            cells = re.findall(r"<td\b.*?</td>", r, re.S)
            cell_text = [strip_tags(c) for c in cells]
            if all(c == "" for c in cell_text):
                continue  # decorative <hr>-only row
            if cell_text and cell_text[0].lower() in ("name", "symbol"):
                continue  # repeated table header row
            entry = {"name": cell_text[0], "meaning": cell_text[1] if len(cell_text) > 1 else ""}
            if len(cell_text) > 2:
                entry["limitations"] = cell_text[2]
            entries.append(entry)
    return entries


def extract_pokertracker_page(path: Path) -> dict:
    content = path.read_text(encoding="utf-8")
    parts = re.split(r"(<dl\b.*?</dl>)", content, flags=re.S)
    category = None
    out: dict[str, list] = {}
    for part in parts:
        dl_match = re.match(r"<dl\b.*?<dt[^>]*>(.*?)</dt>", part, re.S)
        if dl_match:
            category = strip_tags(dl_match.group(1))
            out[category] = []
            continue
        if category is None:
            continue
        divs = re.findall(r'<div class="standard">.*?</div>', part, re.S)
        texts = [strip_tags(d) for d in divs]
        texts = [t for t in texts if t not in ("", "Symbol", "Meaning")]
        for i in range(0, len(texts) - 1, 2):
            out[category].append({"base_name": texts[i], "meaning": texts[i + 1]})
    return out


def main() -> None:
    result: dict = {}
    for fname, label in TABLE_PAGES.items():
        path = SOURCE_DIR / fname
        if not path.exists():
            print(f"warning: missing {path}", file=sys.stderr)
            continue
        result[label] = extract_table_page(path)

    pt_path = SOURCE_DIR / POKERTRACKER_PAGE
    if pt_path.exists():
        result[POKERTRACKER_LABEL] = extract_pokertracker_page(pt_path)
    else:
        print(f"warning: missing {pt_path}", file=sys.stderr)

    json.dump(result, sys.stdout, indent=2, ensure_ascii=False)
    print()


if __name__ == "__main__":
    main()
